// Generates the promo narration with ElevenLabs, one clip per scene, from promo-voiceover.json.
// Writes public/audio/voiceover/<scene>.mp3 and src/promo/voiceover.ts (start + measured duration).
// Needs ELEVENLABS_API_KEY (and optionally ELEVENLABS_VOICE_ID) in the environment or apps/api/.env.
// Run: node scripts/generate-promo-voiceover.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const FREE_VOICES = ['EXAVITQu4vr4xnSDxMaL', '21m00Tcm4TlvDq8ikWAM'];

function envFromApi(name) {
  if (process.env[name]) return process.env[name].trim();
  const file = here('../../api/.env');
  if (!existsSync(file)) return '';
  const line = readFileSync(file, 'utf8')
    .split(/\r?\n/)
    .find((l) => l.startsWith(`${name}=`));
  return line ? line.slice(name.length + 1).trim().replace(/^["']|["']$/g, '') : '';
}

const config = JSON.parse(readFileSync(here('./promo-voiceover.json'), 'utf8'));
const apiKey = envFromApi('ELEVENLABS_API_KEY');
if (!apiKey) {
  console.error('ELEVENLABS_API_KEY is not set (env or apps/api/.env).');
  process.exit(1);
}
const preferred = envFromApi('ELEVENLABS_VOICE_ID');
const voices = [...new Set([preferred.length > 8 ? preferred : null, ...FREE_VOICES].filter(Boolean))];

async function speak(text) {
  let lastError = '';
  for (const voiceId of voices) {
    const res = await fetch(
      `https://api.elevenlabs.io/v1/text-to-speech/${voiceId}/with-timestamps?output_format=mp3_44100_128`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'xi-api-key': apiKey },
        body: JSON.stringify({ text, model_id: config.model, voice_settings: config.voiceSettings }),
      },
    );
    if (res.ok) {
      const data = await res.json();
      const ends = (data.normalized_alignment ?? data.alignment)?.character_end_times_seconds ?? [];
      return { audio: Buffer.from(data.audio_base64, 'base64'), durationSec: ends.at(-1) ?? 0, voiceId };
    }
    lastError = `HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`;
    if (![401, 402, 403].includes(res.status)) break;
  }
  throw new Error(`ElevenLabs TTS failed (${lastError})`);
}

const outDir = here('../public/audio/voiceover/');
mkdirSync(outDir, { recursive: true });
const manifest = {};
for (const [scene, line] of Object.entries(config.lines)) {
  const { audio, durationSec, voiceId } = await speak(line.text);
  writeFileSync(`${outDir}${scene}.mp3`, audio);
  manifest[scene] = { file: `audio/voiceover/${scene}.mp3`, startSec: line.startSec, durationSec: Number(durationSec.toFixed(2)) };
  console.log(`${scene}: ${durationSec.toFixed(2)}s (voice ${voiceId.slice(0, 6)}…) "${line.text}"`);
}

writeFileSync(
  here('../src/promo/voiceover.ts'),
  `// Generated by scripts/generate-promo-voiceover.mjs from scripts/promo-voiceover.json.\n` +
    `export const VOICEOVER = ${JSON.stringify(manifest, null, 2)} as const;\n\n` +
    `export type VoiceoverScene = keyof typeof VOICEOVER;\n`,
);
console.log('wrote src/promo/voiceover.ts');
